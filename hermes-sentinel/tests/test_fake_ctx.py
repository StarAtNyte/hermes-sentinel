def test_spawn_task_outside_loop_raises_like_host(fake_ctx: FakeCtx):
    async def job():
        return 1

    coro = job()
    with pytest.raises(RuntimeError):
        fake_ctx.spawn_task(coro)
    coro.close()
    with pytest.raises(TypeError):
        fake_ctx.spawn_task(lambda: None)  # type: ignore[arg-type]


async def test_spawn_task_uses_running_loop(fake_ctx: FakeCtx):
    async def job():
        return 42

    assert await fake_ctx.spawn_task(job(), name="j") == 42


def test_controlled_loop_helpers_and_cancel_on_unload(fake_ctx: FakeCtx):
    ran: list[str] = []

    async def worker():
        ran.append("started")
        await asyncio.sleep(3600)

    task = fake_ctx.call_in_loop(fake_ctx.spawn_task, worker(), name="watch")
    fake_ctx.run_until_idle()
    assert ran == ["started"] and not task.done()
    assert task.get_name() == "watch"
    fake_ctx.unload()
    assert task.cancelled()


def test_run_awaitable_on_controlled_loop(fake_ctx: FakeCtx):
    async def job():
        await asyncio.sleep(0)
        return "done"

    assert fake_ctx.run(job()) == "done"


def test_unload_runs_callbacks_in_reverse_and_keeps_errors(fake_ctx: FakeCtx):
    order: list[str] = []
    fake_ctx.on_unload(lambda: order.append("first"))

    def broken():
        raise RuntimeError("cleanup failed")

    fake_ctx.on_unload(broken)
    fake_ctx.on_unload(lambda: order.append("third"))
    removed = fake_ctx.on_unload(lambda: order.append("never"))
    removed.dispose()
    fake_ctx.unload()
    assert order == ["third", "first"]
    assert [str(e) for e in fake_ctx.unload_errors] == ["cleanup failed"]
    with pytest.raises(TypeError):
        fake_ctx.on_unload("x")  # type: ignore[arg-type]
