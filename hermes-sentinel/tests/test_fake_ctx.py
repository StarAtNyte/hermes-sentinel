def test_register_tool_and_dispose(fake_ctx: FakeCtx):
    handle = fake_ctx.register_tool("sentinel_look", "sentinel", SCHEMA, _handler)
    assert handle is not None and fake_ctx.registered_capabilities()["tools"] == ["sentinel_look"]
    assert json.loads(fake_ctx.dispatch_tool("sentinel_look", {"q": 1}))["args"] == {"q": 1}
    handle.dispose()
    handle.dispose()  # idempotent
    assert fake_ctx.tools == {}
    assert "Unknown tool" in fake_ctx.dispatch_tool("sentinel_look", {})


