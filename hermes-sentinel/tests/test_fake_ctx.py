def test_valid_hook_and_middleware_no_warning(fake_ctx: FakeCtx):
    cb = lambda **kw: None  # noqa: E731
    h1 = fake_ctx.register_hook("pre_tool_call", cb)
    h2 = fake_ctx.register_middleware("tool_request", cb)
    assert list(fake_ctx.warnings) == []
    assert fake_ctx.registered_capabilities()["hooks"] == ["pre_tool_call"]
    assert fake_ctx.registered_capabilities()["middleware"] == ["tool_request"]
    h1.dispose()
    h2.dispose()
    assert fake_ctx.registered_capabilities() == {"tools": [], "hooks": [], "middleware": []}


