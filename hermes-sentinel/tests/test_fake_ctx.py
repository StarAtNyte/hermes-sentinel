def test_recording_is_thread_safe(fake_ctx: FakeCtx):
    def worker():
        for i in range(200):
            fake_ctx.inject_message(str(i))
            fake_ctx.post_message(str(i))

    threads = [threading.Thread(target=worker) for _ in range(4)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert len(fake_ctx.injected) == len(fake_ctx.posted) == 800


