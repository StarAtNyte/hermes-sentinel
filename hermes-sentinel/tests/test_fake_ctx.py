def test_ctx_has_no_storage_methods(fake_ctx: FakeCtx):
    # Storage is plugins.plugin_storage module functions in Hermes, not ctx methods.
    for name in ("data_dir", "plugin_data_dir", "plugin_db", "data_root"):
        assert not hasattr(fake_ctx, name)


HARNESS_ONLY = {
    "call_in_loop", "call_tool", "close", "registered_capabilities", "run", "run_command",
    "run_until_idle", "unload",
}


def _real_context_members() -> set[str]:
    plugins_py = hermes_agent_dir() / "hermes_cli" / "plugins.py"
    if not plugins_py.is_file():
        pytest.skip("no Hermes checkout to compare against")
    tree = ast.parse(plugins_py.read_text(encoding="utf-8"))
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "PluginContext")
    members = {
        n.name for n in cls.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
    }
    # register_* provider methods generated by _make_scoped_provider_registrar are set later.
    return members


def test_public_members_exist_on_real_context():
    """Every public FakeCtx method a plugin could call also exists on the real PluginContext."""
    real = _real_context_members()
    public = {n for n in dir(FakeCtx) if not n.startswith("_")} - HARNESS_ONLY
    assert public - real == set(), "FakeCtx exposes methods the real PluginContext lacks"


